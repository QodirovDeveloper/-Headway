"""Turn tools/<level>/scan.json into a draft book: hotspots, unit ranges, and a report.

Usage: python tools/resolve.py <level> [units.json]

units.json (optional, hand-made) = {"offset": 1, "units": [[n, "Title", from, to], ...],
"extra": [["W", "Writing", from, to], ...], "fix": {"page:x:y": "T1.2" | null}}
Without it, unit ranges are guessed from the "Unit N •" footers and printed for review.
"""
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TAIL = re.compile(r'(\d{1,2})\s*[.,]\s*(\d{1,2})\s*$')
FOOT = re.compile(r'Unit\s*([0-9Il]{1,2})\s*[•·.,]', re.I)


def parse_label(raw: str):
    if not raw.startswith('?'):
        return raw
    m = TAIL.search(raw[1:])
    return f'T{int(m[1])}.{int(m[2])}' if m else None


def main(level: str, units_path: str | None):
    scan = json.loads((ROOT / 'tools' / level / 'scan.json').read_text(encoding='utf-8'))
    posts = json.loads((ROOT / 'tools' / 'posts.json').read_text()).get(level, {})
    cfg = json.loads(Path(units_path).read_text(encoding='utf-8')) if units_path else None

    if not cfg:
        guess, titles = {}, defaultdict(list)
        for p in scan:
            txt = p['foot'] + ' ' + p['head']
            m = re.search(r'Unit\s*([0-9Il]{1,2})\s*[•·.,]\s*([A-Za-z][^0-9]{2,40}?)(?:\s+\d|$|\s{2})', txt)
            m = m or FOOT.search(txt)
            if m:
                u = int(m[1].replace('I', '1').replace('l', '1'))
                guess[p['n']] = u
                if m.lastindex and m.lastindex >= 2:
                    titles[u].append(m[2].strip(' .'))
        print('page -> unit (from footers):')
        print(' '.join(f'{k}:{v}' for k, v in sorted(guess.items())))
        # Draft ranges: each unit runs until the next unit's first footer page.
        firsts = {}
        for pg, u in sorted(guess.items()):
            firsts.setdefault(u, pg)
        us = sorted(firsts)
        draft = []
        for i, u in enumerate(us):
            a = firsts[u] - 1 if i else firsts[u]
            if i and draft:
                draft[-1][3] = a - 1
            last = max(pg for pg, uu in guess.items() if uu == u)
            title = max(set(titles[u]), key=titles[u].count) if titles[u] else f'Unit {u}'
            draft.append([u, title, a, last])
        for d in draft:
            print(d)
        for p in scan:
            if p['n'] > draft[-1][3] and re.search(r'Writing|Tapescript|Audioscript|Grammar Reference|Word list', p['head'] + p['foot'], re.I):
                print('extra?', p['n'], ascii(p['head'][:60]))
        return

    fixes = cfg.get('fix', {})
    unit_of_page = {}
    for n, _, a, b in cfg['units']:
        for p in range(a, b + 1):
            unit_of_page[p] = n

    pages = defaultdict(list)
    found = defaultdict(list)
    report = []
    for p in scan:
        for raw, x, y, w, h in p['labels']:
            key = f"{p['n']}:{round(x)}:{round(y)}"
            t = fixes[key] if key in fixes else parse_label(raw)
            if not t:
                continue
            if t not in posts:
                report.append(f'no audio for {t} on p{p["n"]} ({key})')
                continue
            u = unit_of_page.get(p['n'])
            unit_t = int(t[1:].split('.')[0])
            if u is not None and u != unit_t:
                report.append(f'{t} on p{p["n"]} but page is unit {u} ({key}, raw {ascii(raw)})')
            pages[p['n']].append([t, x, y, w, h])
            found[t].append(p['n'])

    # Hand-placed labels the detector missed: [page, track, x, y, w, h] in page %.
    for pg, t, x, y, w, h in cfg.get('add', []):
        pages[pg].append([t, x, y, w, h])
        found[t].append(pg)

    missing = [t for t in posts if t not in found]
    book = {
        'pages': {str(k): v for k, v in sorted(pages.items())},
        'ratio': {str(p['n']): p['ratio'] for p in scan},
        'units': [{'n': n, 'title': t, 'from': a, 'to': b} for n, t, a, b in cfg['units']],
        'extra': [{'n': n, 'title': t, 'from': a, 'to': b} for n, t, a, b in cfg.get('extra', [])],
        'posts': posts,
        'channel': 'Headway4thEdition',
        'pageOffset': cfg['offset'],
    }
    out = ROOT / 'src' / 'data' / level
    out.mkdir(parents=True, exist_ok=True)
    (out / 'book.ts').write_text(
        "// Generated by tools/resolve.py — page hotspots, page ratios, units, and Telegram post ids.\n"
        "import type { Book } from '../types';\n\n"
        f"export const BOOK: Book = {json.dumps(book, ensure_ascii=False)};\n",
        encoding='utf-8',
    )
    if not (out / 'answers.ts').exists():
        (out / 'answers.ts').write_text(
            "import type { Answer } from '../types';\n\nexport const ANSWERS: Answer[] = [];\n", encoding='utf-8')
    if not (out / 'index.ts').exists():
        (out / 'index.ts').write_text(
            "import type { LevelData } from '../types';\nimport { ANSWERS } from './answers';\n"
            "import { BOOK } from './book';\n\nconst data: LevelData = { book: BOOK, answers: ANSWERS };\n"
            "export default data;\n", encoding='utf-8')

    print(f'{level}: {sum(len(v) for v in pages.values())} hotspots, {len(found)}/{len(posts)} tracks placed')
    print('missing:', ' '.join(missing) or '-')
    for r in report:
        print(' !', r)


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else None)
